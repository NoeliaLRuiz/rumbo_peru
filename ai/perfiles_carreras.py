_COMPILADAS = [(c, re.compile("|".join(rf"(?:\b{k})" if not k.startswith("^") else k for k in c["claves"])))
               for c in CARRERAS]


def buscar_carrera(programa: str) -> dict | None:
    """Devuelve el perfil de la carrera que corresponde al nombre del programa, o None."""
    nombre = normalizar(programa)
    for carrera, patron in _COMPILADAS:
        if patron.search(nombre):
            return carrera
    return None
